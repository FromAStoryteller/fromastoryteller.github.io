"""Rebuild public media derivatives; originals and licences remain unchanged.
Requires Pillow (with AVIF), fonttools/brotli and ffmpeg.
"""
from pathlib import Path
import json,re,subprocess
from PIL import Image,ImageOps
from fontTools import subset
root=Path(__file__).resolve().parent.parent
variants={}
for source in sorted((root/'assets/images').rglob('*')):
 if source.suffix.lower() not in ('.jpg','.jpeg','.png') or 'responsive' in source.parts:continue
 with Image.open(source) as original:
  image=ImageOps.exif_transpose(original).convert('RGB'); entries={}
  for width in [480,800,1200,1600]:
   if width>image.width:continue
   resized=image.resize((width,round(image.height*width/image.width)),Image.Resampling.LANCZOS)
   for fmt,quality in [('webp',80),('avif',55)]:
    target=root/'assets/images/responsive'/source.relative_to(root/'assets/images').with_suffix(f'.{width}.{fmt}');target.parent.mkdir(parents=True,exist_ok=True)
    if not target.exists() or target.stat().st_mtime<source.stat().st_mtime:resized.save(target,format=fmt.upper(),quality=quality,**({'method':6} if fmt=='webp' else {'speed':6}))
    entries.setdefault(fmt,[]).append({'width':width,'src':'/'+target.relative_to(root).as_posix()})
  if entries:variants['/'+source.relative_to(root).as_posix()]=entries
(root/'systems/content/image-variants.mjs').write_text('// Generated by scripts/optimise-media.py.\nexport const imageVariants='+json.dumps(variants,separators=(',',':'))+';\n')
latin='U+0000-024F,U+1E00-1EFF,U+2000-206F,U+20A0-20CF'
for source in sorted((root/'assets/fonts').rglob('*.woff2')):
 if '.latin.' in source.name:continue
 options=subset.Options();options.flavor='woff2';options.layout_features=['*'];options.name_IDs=['*'];options.name_legacy=True
 font=subset.load_font(str(source),options);subsetter=subset.Subsetter(options=options);subsetter.populate(unicodes=subset.parse_unicodes(latin));subsetter.subset(font);subset.save_font(font,str(source.with_name(source.stem+'.latin.woff2')),options)
# Keep the full icon library available for immutable policy snapshots. Public
# pages use the same accessible icon markup with only the glyphs the site uses.
used={'fa-instagram','fa-facebook','fa-tiktok','fa-youtube','fa-x-twitter','fa-link','fa-xmark','fa-share-nodes'}
for folder in ['systems','account','components','sources','stories','tools','games','search','css','_templates']:
 for source in (root/folder).rglob('*'):
  if source.suffix in ('.js','.mjs','.html','.css','.json') and 'policy-history' not in source.parts:
   used.update(re.findall(r'\bfa-[a-z0-9-]+',source.read_text(errors='ignore')))
css='\n'.join((root/'assets/fontawesome/css'/name).read_text() for name in ['fontawesome.min.css','brands.min.css','solid.min.css'])
codes=set()
def rule(match):
 selectors,body=match.groups()
 if '--fa:' not in body:return match.group(0)
 kept=[s for s in selectors.split(',') if any(name in used for name in re.findall(r'\.([a-z0-9-]+)',s))]
 if not kept:return ''
 codes.update(int(x,16) for x in re.findall(r'\\([a-f0-9]{3,6})',body))
 return ','.join(kept)+'{'+body+'}'
css=re.sub(r'([^{}]+)\{([^{}]+)\}',rule,css)
for kind,name in [('solid','fa-solid-900'),('brands','fa-brands-400')]:
 source=root/'assets/fontawesome/webfonts'/f'{name}.woff2';target=source.with_name(f'site-{kind}.woff2');options=subset.Options();options.flavor='woff2'
 font=subset.load_font(str(source),options);subsetter=subset.Subsetter(options=options);subsetter.populate(unicodes=codes);subsetter.subset(font);subset.save_font(font,str(target),options)
 css=css.replace(name+'.woff2','site-'+kind+'.woff2')
(root/'assets/fontawesome/css/site-icons.css').write_text(css)
for source in sorted((root/'assets/sounds').rglob('*.wav')):
 subprocess.run(['ffmpeg','-nostdin','-loglevel','error','-y','-i',str(source),'-codec:a','libmp3lame','-q:a','4',str(source.with_suffix('.mp3'))],check=True)
print(f'Generated responsive images for {len(variants)} sources, Latin fonts, {len(codes)} icon glyphs and compressed audio.')
